const cityIds = new Set(cities.map((c) => c.id));

function haversineMiles(a, b) {
  const R = 3958.8;
  const toRad = (d) => (d * Math.PI) / 180;
  const dLat = toRad(b.lat - a.lat);
  const dLon = toRad(b.lon - a.lon);
  const lat1 = toRad(a.lat);
  const lat2 = toRad(b.lat);
  const h =
    Math.sin(dLat / 2) ** 2 + Math.cos(lat1) * Math.cos(lat2) * Math.sin(dLon / 2) ** 2;
  return Math.round(R * 2 * Math.asin(Math.sqrt(h)));
}

const byId = Object.fromEntries(cities.map((c) => [c.id, c]));
const edgeKey = (a, b) => [a, b].sort().join("|");
const edges = new Map();

for (const [from, to, terrain] of corridors) {
  if (!cityIds.has(from) || !cityIds.has(to)) continue;
  const key = edgeKey(from, to);
  if (edges.has(key)) continue;
  const miles = Math.max(40, haversineMiles(byId[from], byId[to]));
  edges.set(key, {
    from,
    to,
    terrain,
    miles,
  });
}

// Ensure connectivity: if any city is isolated, link to nearest
function neighbors(id) {
  const n = [];
  for (const e of edges.values()) {
    if (e.from === id) n.push(e.to);
    if (e.to === id) n.push(e.from);
  }
  return n;
}

for (const city of cities) {
  if (neighbors(city.id).length > 0) continue;
  let best = null;
  let bestD = Infinity;
  for (const other of cities) {
    if (other.id === city.id) continue;
    const d = haversineMiles(city, other);
    if (d < bestD) {
      bestD = d;
      best = other;
    }
  }
  if (best) {
    edges.set(edgeKey(city.id, best.id), {
      from: city.id,
      to: best.id,
      terrain: "secondary",
      miles: Math.max(40, bestD),
    });
  }
}

